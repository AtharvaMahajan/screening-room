def insert_genre_taxonomy() -> None:
    known_slugs = {slug for slug, _ in GENRES}
    mapped_slugs = {
        slug for genres in TMDB_GENRES.values() for _, slugs in genres.values() for slug in slugs
    }
    # A typo here would silently map a TMDB genre to nothing: refuse instead.
    assert mapped_slugs == known_slugs, (mapped_slugs ^ known_slugs, "mapping/genre mismatch")

    genres = sa.table("genres", sa.column("slug", sa.Text), sa.column("name", sa.Text))
    op.bulk_insert(genres, [{"slug": slug, "name": name} for slug, name in GENRES])

    insert_mapping = sa.text(
        "INSERT INTO provider_genre_map (provider, media_type, provider_genre_id, genre_id) "
        "SELECT 'tmdb', :media_type, :provider_genre_id, id FROM genres WHERE slug = :slug"
    )
    for media_type, genres_by_id in TMDB_GENRES.items():
        for provider_genre_id, (_tmdb_name, slugs) in genres_by_id.items():
            for slug in slugs:
                op.execute(
                    insert_mapping.bindparams(
                        media_type=media_type, provider_genre_id=provider_genre_id, slug=slug
                    )
                )


